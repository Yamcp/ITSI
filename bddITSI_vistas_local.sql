SELECT 
    ID_PERIODO_ACADEMICO,
    CONCAT(LPAD(MES_INICIO, 2, '0'), '/', AÑO_INICIO, ' - ', LPAD(MES_FIN, 2, '0'), '/', AÑO_FIN) AS NOMBRE_PERIODO,

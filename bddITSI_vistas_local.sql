    STR_TO_DATE(CONCAT(AÑO_INICIO, '-', LPAD(MES_INICIO, 2, '0'), '-01'), '%Y-%m-%d') AS FECHA_INICIO,
    LAST_DAY(STR_TO_DATE(CONCAT(AÑO_FIN, '-', LPAD(MES_FIN, 2, '0'), '-01'), '%Y-%m-%d')) AS FECHA_FIN,
    'N/D' AS TIPO_PERIODO,
